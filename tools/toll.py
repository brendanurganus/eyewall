# Build src/toll.js: human toll and damage per storm from the NHC/CPHC Tropical Cyclone Reports.
# Inputs: tools/toll_review.txt (hand-checked entries) and a sections.json made from the report PDFs
# (pdftotext; "Casualty and Damage Statistics" sections; automatic "none reported" classification).
# usage: python3 tools/toll.py <sections.json> <view.json> data/eyewall_storms.csv src/toll.js
import json, sys, csv

secs, view, storms_csv, out = sys.argv[1:5]
D = json.load(open(secs)); V = json.load(open(view))
files, cls = D['files'], V['cls']
rev = {}
for line in open('tools/toll_review.txt', encoding='utf-8'):
    if line.startswith('#') or not line.strip(): continue
    sid, deaths, damage, note = (line.rstrip('\n').split('|') + [''])[:4]
    rev[sid] = {'deaths': deaths, 'damage': damage, 'note': note}
CROSS = {'EP042022': 'AL022022', 'EP182022': 'AL132022', 'EP222016': 'AL162016'}  # crossed from the Atlantic
storms = [r for r in csv.DictReader(open(storms_csv)) if r['preliminary'] == 'False']
res, n = {}, {'reviewed': 0, 'none': 0, 'brief': 0, 'missing': 0}
for s in storms:
    sid = s['id']; src = CROSS.get(sid, sid); pdf = files.get(src)
    if src in rev:
        e = dict(rev[src]); n['reviewed'] += 1
        if src != sid: e['note'] = (e['note'] + ' ' if e['note'] else '') + 'Covered by the report for its Atlantic phase.'
    elif cls.get(src) == 'none':
        e = {'deaths': 'None reported', 'damage': 'None reported', 'note': ''}; n['none'] += 1
    elif pdf:  # short depression reports without a casualty section, and no deaths mentioned anywhere
        e = {'deaths': 'None reported', 'damage': 'None reported', 'note': 'Brief report without a casualty section.'}; n['brief'] += 1
    else:
        e = {'deaths': 'Not compiled', 'damage': 'Not compiled', 'note': 'The 2005-06 Central Pacific reports were published by CPHC, not in the NHC archive used here.'}; n['missing'] += 1
    if pdf: e['pdf'] = pdf
    res[sid] = {k: v for k, v in e.items() if v}
open(out, 'w', encoding='utf-8').write('// Generated by tools/toll.py from NHC/CPHC Tropical Cyclone Reports (public domain).\nexport default ' + json.dumps(res, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(n, len(res))
