# Write src/satindex.js from a tools/satlib.py output folder. Katrina keeps the hand-registered Stage 2
# images in src/sat (higher resolution); build.mjs copies both into dist/sat/<id>/.
# usage: python3 tools/satindex.py <satlib dir>
import json, sys, os
idx = json.load(open(os.path.join(sys.argv[1], 'index.json')))
k = json.load(open('src/sat/meta.json'))
idx['AL122005'] = {'t': 1125246300000, 'src': 'MODIS Terra + Aqua (hand-registered)', 'wide': k['wide'], 'core': k['core'], 'eye': k['eye'], 'eyeFound': True}
for v in idx.values():
    for f in ('contrast', 'gaps'): v.pop(f, None)
open('src/satindex.js', 'w').write('// Generated by tools/satindex.py: NASA snapshots available per storm (images in dist/sat/<id>/).\nexport default ' + json.dumps(idx, separators=(',', ':')) + ';\n')
print(len(idx), 'storms with photos')
