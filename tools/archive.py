# Build src/archive.js: every finalised storm 2005-2025 (preliminary 2026 rows excluded, owner decision),
# compact columnar tracks with the fields stormAt() needs, plus NOAA aircraft eye fixes.
# usage: python3 tools/archive.py data src/archive.js
import csv, json, sys, os
from collections import defaultdict

src, out = sys.argv[1], sys.argv[2]
storms = [r for r in csv.DictReader(open(os.path.join(src, 'eyewall_storms.csv'))) if r['preliminary'] == 'False']
keep = {r['id'] for r in storms}
pts = defaultdict(list)
for r in csv.DictReader(open(os.path.join(src, 'eyewall_track_points.csv'))):
    if r['id'] in keep and r['preliminary'] in ('0', 'False'):
        pts[r['id']].append(r)
eyes = json.load(open(os.path.join(src, 'aircraft_eyes.json')))

def num(v, scale=1):
    if v in ('', None): return None
    return round(float(v) * scale)

def title(n):
    return ' '.join(w.capitalize() for w in n.split(' ')) if n else n

res = []
for s in storms:
    P = pts[s['id']]
    assert len(P) == int(s['n_pts']), s['id']
    col = lambda k, sc=1: [num(p[k], sc) for p in P]
    res.append({
        'id': s['id'], 'name': title(s['name']), 'basin': s['basin'], 'year': int(s['year']),
        'peak': int(s['peak_kt']), 'cat': s['peak_cat'], 'pmin': num(s['min_mb']),
        't': [p['time_utc'] for p in P],                  # YYYYMMDDHHMM
        'rec': [p['record'] or '' for p in P], 'st': [p['status'] for p in P],
        'lat': col('lat', 10), 'lon': col('lon', 10),     # tenths of a degree
        'v': col('vmax_kt'), 'p': col('pmin_mb'),
        'r34': [[num(p['r34_' + q]) for q in ('ne', 'se', 'sw', 'nw')] for p in P],
        'r50': [[num(p['r50_' + q]) for q in ('ne', 'se', 'sw', 'nw')] for p in P],
        'r64': [[num(p['r64_' + q]) for q in ('ne', 'se', 'sw', 'nw')] for p in P],
        'rmw': col('rmw_nm'), 'poci': col('poci_mb'), 'roci': col('roci_nm'),
        'eyes': [[e['t'], e['d'], e['d2'] or e['d']] for e in eyes.get(s['id'], []) if e.get('d')],
    })
open(out, 'w').write('// Generated by tools/archive.py from data/ (NOAA HURDAT2, b-decks, f-decks; public domain).\nexport default ' + json.dumps(res, separators=(',', ':')) + ';\n')
print(len(res), 'storms,', sum(len(r['t']) for r in res), 'points,', os.path.getsize(out) // 1024, 'KB')
